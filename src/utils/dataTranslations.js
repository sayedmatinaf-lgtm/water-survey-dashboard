export function translateCategory(domain, key, lang = 'en') {
  if (!key) return '';
  const domainObj = categoryTranslations[domain];
  if (domainObj && domainObj[key]) {
    return domainObj[key][lang] || domainObj[key]['en'] || key;
  }
  return key;
}